#!/usr/bin/env python3
"""Emit calibrated Float32 constants; no runtime high-precision DSP."""
from pathlib import Path
import math
import struct


OUTPUT = Path(__file__).resolve().parents[1] / 'projects/Synth2/src/dsp'


def f32(value):
    return struct.unpack('f', struct.pack('f', value))[0]


def literal(value):
    return f32(value).hex() + 'f'


def header(description):
    return ['#pragma once', '#include <array>', '', '// ' + description,
            'namespace synth2::dsp', '{']


def float_array(lines, name, values):
    lines.append(f'    inline constexpr std::array<float,{len(values)}> {name} {{')
    for at in range(0, len(values), 4):
        lines.append('        ' + ','.join(map(literal, values[at:at + 4])) + ',')
    lines.append('    };')


def write_header(name, lines):
    (OUTPUT / name).write_text('\n'.join([*lines, '}']) + '\n')


def waveform_constants():
    sine = [f32(math.sin(2 * math.pi * i / 2048)) for i in range(2048)]
    borders = []
    previous = -1
    harmonics = 1
    for i in range(36):
        x = f32(i * f32(1 / 36))
        frequency = f32(math.exp(math.log(512) * x) * 27.5)
        harmonics = int(max(f32(22050 / frequency), 1))
        if harmonics < 16:
            break
        if harmonics != previous:
            borders.append(frequency)
        previous = harmonics
    borders += [f32(22050 / h) for h in range(harmonics, 0, -1)]

    lines = header('Generated by tools/generate_oscillator_constants.py. Float32 waveform words.')
    float_array(lines, 'oscillatorSine', sine)
    float_array(lines, 'oscillatorSineResidual', [
        f32(math.sin(2 * math.pi * i / 2048) - sine[i]) for i in range(2048)])
    float_array(lines, 'oscillatorBorders', borders)
    float_array(lines, 'midiFrequencyWords', [
        f32(440 * 2 ** ((note - 69) / 12)) for note in range(128)] + [.5])
    float_array(lines, 'pitchRatioWords', [
        f32(math.exp(math.log(2) * f32(i * f32(1 / 128)))) for i in range(-128, 129)])
    lines.append('    inline constexpr float sinePeriodResidual=' + literal(math.sin(2 * math.pi)) + ';')
    for name, value in [('inversePi', 1 / math.pi), ('inversePiSquared', (1 / math.pi) ** 2)]:
        high = f32(value)
        low = f32(value - high)
        lines.append(f'    inline constexpr float {name}High={literal(high)},{name}Low={literal(low)};')
    write_header('OscillatorConstants.h', lines)


def fm_constants():
    lines = header('Generated Float32-coordinate to integer phase-word calibration.')
    lines.append('    inline constexpr std::array<int,65025> fmDepthWords {')
    words = [int((math.exp(math.log(1000) * f32((i / 512) * f32(1 / 127))) - 1)
                 * (1 / 999) * 67108864) for i in range(65025)]
    for at in range(0, len(words), 8):
        lines.append('        ' + ','.join(map(str, words[at:at + 8])) + ',')
    lines.append('    };')
    write_header('FmTables.h', lines)


def exp2_constants():
    lines = header('Generated Float32 high/residual words for 2^(k/4096), k=-2048..2048.')
    lines.append('    inline constexpr std::array<std::array<float,2>,4097> exp2Words {{')
    for i in range(-2048, 2049):
        value = 2 ** (i / 4096)
        high = f32(value)
        low = f32(value - high)
        lines.append('        {' + literal(high) + ',' + literal(low) + '},')
    lines.append('    }};')
    write_header('FloatMathTables.h', lines)


def control_constants():
    controls = {'chorusTimeWords': [], 'chorusDepthWords': [], 'chorusRateWords': [],
                'delaySpreadWords': [], 'phaserSpeedWords': [], 'ringFrequencyWords': [],
                'lfoRateWords': []}
    for i in range(128):
        normalized = f32(i * f32(1 / 127))
        milliseconds = f32(normalized * 30) if normalized >= .5 else 300 ** ((normalized * 2) ** .6) * .05
        controls['chorusTimeWords'].append(f32(milliseconds * .001))
        controls['chorusDepthWords'].append(f32((100 ** normalized - 1) * (1 / 99)))
        controls['chorusRateWords'].append(f32(.01 if i == 0 else 20000 ** normalized * .02))
        norm = min(1, f32(abs((i - 64) * (1 / 63))))
        controls['delaySpreadWords'].append(f32(0 if i == 64 else (-1 if i < 64 else 1) * 1000 ** norm * .0001))
        controls['phaserSpeedWords'].append(f32(.01 if i == 0 else 1000 ** normalized * .02))
        controls['ringFrequencyWords'].append(f32(8000 ** normalized))
        controls['lfoRateWords'].append(f32(1500 ** (i / 127) / 12))
    lines = header('Generated compatible Float32 control words; no runtime double arithmetic.')
    for name, values in controls.items():
        float_array(lines, name, values)
    write_header('ControlTables.h', lines)


def main():
    waveform_constants()
    fm_constants()
    exp2_constants()
    control_constants()


if __name__ == '__main__':
    main()
