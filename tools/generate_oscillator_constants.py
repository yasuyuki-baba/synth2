#!/usr/bin/env python3
"""Emit calibrated Float32 waveform constants; no runtime high-precision DSP."""
from pathlib import Path
import math,struct

def f32(value):return struct.unpack('f',struct.pack('f',value))[0]
def literal(value):return f32(value).hex()+'f'
def main():
    sine=[f32(math.sin(2*math.pi*i/2048)) for i in range(2048)]
    borders=[];previous=-1;harmonics=1
    for i in range(36):
        x=f32(i*f32(1/36));frequency=f32(math.exp(math.log(512)*x)*27.5)
        harmonics=int(max(f32(22050/frequency),1))
        if harmonics<16:break
        if harmonics!=previous:borders.append(frequency)
        previous=harmonics
    borders += [f32(22050/h) for h in range(harmonics,0,-1)]
    out=['#pragma once','#include <array>','','// Generated by tools/generate_oscillator_constants.py. Float32 waveform words.',
         'namespace synth2::dsp','{']
    for name,values in [('oscillatorSine',sine),('oscillatorBorders',borders)]:
        out.append(f'    inline constexpr std::array<float,{len(values)}> {name} {{')
        for at in range(0,len(values),4):out.append('        '+','.join(map(literal,values[at:at+4]))+',')
        out.append('    };')
    for name,value in [('inversePi',1/math.pi),('inversePiSquared',(1/math.pi)**2)]:
        high=f32(value);low=f32(value-high)
        out.append(f'    inline constexpr float {name}High={literal(high)},{name}Low={literal(low)};')
    out.append('}')
    (Path(__file__).resolve().parents[1]/'projects/Synth2/src/dsp/OscillatorConstants.h').write_text('\n'.join(out)+'\n')
    fm=['#pragma once','#include <array>','','// Generated Float32-coordinate to integer phase-word calibration.',
        'namespace synth2::dsp','{','    inline constexpr std::array<int,65025> fmDepthWords {']
    words=[int((math.exp(math.log(1000)*f32((i/512)*f32(1/127)))-1)*(1/999)*67108864) for i in range(65025)]
    for at in range(0,len(words),8):fm.append('        '+','.join(map(str,words[at:at+8]))+',')
    fm+=['    };','}']
    (Path(__file__).resolve().parents[1]/'projects/Synth2/src/dsp/FmTables.h').write_text('\n'.join(fm)+'\n')
if __name__=='__main__':main()
